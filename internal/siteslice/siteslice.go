// Package siteslice keeps one systemd slice per site with its CPU, memory and
// process limits (ADR-0015): hostashi-site-<user>.slice below
// hostashi-site.slice. The site's PHP-FPM master, cron jobs and services
// run in it, so a runaway site hits its own ceiling first. The agent writes
// the slice unit files; a Controller makes systemd read them.
package siteslice

import (
	"bufio"
	"bytes"
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"sync"

	"github.com/maki-it/hostashi/internal/agentapi"
)

// DefaultDir is where the slice units go.
const DefaultDir = "/etc/systemd/system"

// Name is the slice of a site: "-" in the user is escaped the way
// systemd-escape does, because a dash in a slice name means nesting.
func Name(user string) string {
	return "hostashi-site-" + strings.ReplaceAll(user, "-", `\x2d`) + ".slice"
}

// Limits of one site. Zero values mean: no limit (memory, tasks, CPU quota)
// or the systemd default weight of 100 (CPU weight).
type Limits struct {
	MemoryMax       uint64 // bytes; MemoryHigh is 90 percent of it
	TasksMax        uint64
	CPUWeight       uint64 // 1 to 10000
	CPUQuotaPercent uint64 // 100 = one full CPU
}

// FromAPI converts the agent request values.
func FromAPI(l agentapi.SiteLimits) Limits {
	return Limits{MemoryMax: l.MemoryMax, TasksMax: l.TasksMax, CPUWeight: l.CPUWeight, CPUQuotaPercent: l.CPUQuotaPercent}
}

// API converts to the agent response values.
func (l Limits) API() agentapi.SiteLimits {
	return agentapi.SiteLimits{MemoryMax: l.MemoryMax, TasksMax: l.TasksMax, CPUWeight: l.CPUWeight, CPUQuotaPercent: l.CPUQuotaPercent}
}

// DefaultControlDir is where systemctl set-property --runtime keeps its
// drop-ins.
const DefaultControlDir = "/run/systemd/system.control"

// Controller makes systemd read changed unit files and applies the limits
// to a running slice (phpctl on a server).
type Controller interface {
	DaemonReload(ctx context.Context) error
	// SetSliceProperties applies properties to the slice now, for this
	// boot only (systemctl set-property --runtime). A daemon-reload alone
	// leaves the running cgroup unchanged.
	SetSliceProperties(ctx context.Context, slice string, props []string) error
}

// Manager writes and removes the slice units.
type Manager struct {
	Dir string
	Ctl Controller
	// ControlDir holds the runtime drop-ins of SetSliceProperties, removed
	// with the slice. Empty: leave them (they vanish on reboot).
	ControlDir string

	mu sync.Mutex
}

func (m *Manager) path(user string) string { return filepath.Join(m.Dir, Name(user)) }

// Render returns the unit file of a site's slice.
func Render(user string, l Limits) ([]byte, error) {
	if err := agentapi.ValidateSiteUser(user); err != nil {
		return nil, err
	}

	if err := l.API().Validate(); err != nil {
		return nil, err
	}

	var b bytes.Buffer

	fmt.Fprintf(&b, "# Generated by the Hostashi agent for site %s (ADR-0015). Do not edit: changes are overwritten.\n", user)
	fmt.Fprint(&b, "[Unit]\nDescription=Hostashi site "+user+"\n\n[Slice]\n")
	fmt.Fprint(&b, "MemoryAccounting=yes\nTasksAccounting=yes\n")

	for _, p := range l.properties() {
		if p == "CPUQuota=" {
			continue
		}

		fmt.Fprint(&b, p+"\n")
	}

	return b.Bytes(), nil
}

// properties are the limit settings of the slice, the same in the unit
// file and for SetSliceProperties. "CPUQuota=" (no quota) resets a quota
// set before.
func (l Limits) properties() []string {
	weight := l.CPUWeight
	if weight == 0 {
		weight = 100
	}

	quota := ""
	if l.CPUQuotaPercent > 0 {
		quota = strconv.FormatUint(l.CPUQuotaPercent, 10) + "%"
	}

	memHigh, memMax, tasks := "infinity", "infinity", "infinity"
	if l.MemoryMax > 0 {
		memHigh = strconv.FormatUint(l.MemoryMax/10*9, 10)
		memMax = strconv.FormatUint(l.MemoryMax, 10)
	}

	if l.TasksMax > 0 {
		tasks = strconv.FormatUint(l.TasksMax, 10)
	}

	return []string{
		"CPUWeight=" + strconv.FormatUint(weight, 10),
		"CPUQuota=" + quota,
		"MemoryHigh=" + memHigh,
		"MemoryMax=" + memMax,
		"TasksMax=" + tasks,
	}
}

// Set writes the slice of a site, makes systemd read it and applies the
// limits to the running slice: a daemon-reload updates the unit's
// properties but not the cgroup of a slice that is already running. An
// unchanged file is not written again, but the limits are applied anyway,
// so a retry after a failed apply completes it.
func (m *Manager) Set(ctx context.Context, user string, l Limits) error {
	content, err := Render(user, l)
	if err != nil {
		return err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	if old, err := os.ReadFile(m.path(user)); err != nil || !bytes.Equal(old, content) {
		if err := writeAtomic(m.path(user), content); err != nil {
			return err
		}

		if err := m.Ctl.DaemonReload(ctx); err != nil {
			return err
		}
	}

	return m.Ctl.SetSliceProperties(ctx, Name(user), l.properties())
}

// Get returns the limits of a site, and false if it has no slice file.
func (m *Manager) Get(user string) (Limits, bool, error) {
	if err := agentapi.ValidateSiteUser(user); err != nil {
		return Limits{}, false, err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	raw, err := os.ReadFile(m.path(user))
	if errors.Is(err, fs.ErrNotExist) {
		return Limits{}, false, nil
	}

	if err != nil {
		return Limits{}, false, fmt.Errorf("siteslice: %w", err)
	}

	l, err := parse(raw)
	if err != nil {
		return Limits{}, false, fmt.Errorf("siteslice: %s: %w", Name(user), err)
	}

	return l, true, nil
}

// Remove deletes the slice of a deleted site.
func (m *Manager) Remove(ctx context.Context, user string) error {
	if err := agentapi.ValidateSiteUser(user); err != nil {
		return err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	if m.ControlDir != "" {
		if err := os.RemoveAll(filepath.Join(m.ControlDir, Name(user)+".d")); err != nil {
			return fmt.Errorf("siteslice: %w", err)
		}
	}

	err := os.Remove(m.path(user))
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}

	if err != nil {
		return fmt.Errorf("siteslice: %w", err)
	}

	return m.Ctl.DaemonReload(ctx)
}

// parse reads back a file written by Render.
func parse(raw []byte) (Limits, error) {
	var l Limits

	num := func(v string) (uint64, error) {
		if v == "infinity" {
			return 0, nil
		}

		return strconv.ParseUint(v, 10, 64)
	}

	sc := bufio.NewScanner(bytes.NewReader(raw))
	for sc.Scan() {
		k, v, ok := strings.Cut(sc.Text(), "=")
		if !ok {
			continue
		}

		var err error

		switch k {
		case "MemoryMax":
			l.MemoryMax, err = num(v)
		case "TasksMax":
			l.TasksMax, err = num(v)
		case "CPUWeight":
			l.CPUWeight, err = num(v)
			if l.CPUWeight == 100 {
				l.CPUWeight = 0
			}
		case "CPUQuota":
			l.CPUQuotaPercent, err = num(strings.TrimSuffix(v, "%"))
		}

		if err != nil {
			return Limits{}, fmt.Errorf("%s: %w", k, err)
		}
	}

	return l, sc.Err()
}

func writeAtomic(name string, data []byte) error {
	tmp := name + ".tmp"

	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_TRUNC|os.O_EXCL, 0o644)
	if err != nil {
		if errors.Is(err, fs.ErrExist) {
			_ = os.Remove(tmp)

			f, err = os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
		}

		if err != nil {
			return fmt.Errorf("siteslice: %w", err)
		}
	}

	_, werr := f.Write(data)
	if werr == nil {
		werr = f.Sync()
	}

	if cerr := f.Close(); werr == nil {
		werr = cerr
	}

	if werr == nil {
		werr = os.Rename(tmp, name)
	}

	if werr != nil {
		_ = os.Remove(tmp)

		return fmt.Errorf("siteslice: %w", werr)
	}

	return nil
}
