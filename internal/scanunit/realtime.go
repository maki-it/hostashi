// The real-time mode (ADR-0064): clamd and clamonacc from the
// distribution. clamav-install (instance realtime-on) installs
// clamav-daemon and clamdscan and writes drop-ins that start both with
// RealtimeConfig instead of the distribution's clamd.conf, clamonacc with
// --fdpass, report only and its log in RealtimeLog. The agent writes
// RealtimeConfig from the sites it is told about and reads the log.
const (
	// DefaultRealtimeConfig is the clamd.conf of the real-time mode.
	DefaultRealtimeConfig = "/etc/hostashi/clamav/clamd.conf"
	// DefaultRealtimeLog is clamonacc's log (root 0600, in DefaultLogDir).
	DefaultRealtimeLog = "/var/log/hostashi/scan/realtime.log"
	// RealtimeSocket is where clamav-daemon.socket listens.
	RealtimeSocket = "/run/clamav/clamd.ctl"
	// Clamdscan scans through clamd while the real-time mode is on, so the
	// signatures are not loaded twice.
	Clamdscan = "/usr/bin/clamdscan"

	// EngineRealtimeOn and EngineRealtimeOff are the install unit's
	// instances for the real-time mode.
	EngineRealtimeOn  = "realtime-on"
	EngineRealtimeOff = "realtime-off"

	// The distribution's units, with Hostashi's drop-ins.
	ClamdUnit     = "clamav-daemon.service"
	ClamonaccUnit = "clamav-clamonacc.service"

	// maxRealtimeRead is how much of the log one poll reads.
	maxRealtimeRead = 1 << 20
	// realtimeLogKeep: a log read to its end and larger than this is
	// emptied (clamonacc appends, so it goes on writing at the start).
	realtimeLogKeep = 4 << 20
)

// RealtimeController restarts and reads the distribution's units
// (phpctl.ClamAVRealtimeUnits).
type RealtimeController interface {
	Restart(ctx context.Context, unit string) error
	State(ctx context.Context, unit string) (string, error)
}

// Realtime keeps clamonacc's configuration in step with the sites and
// reads what it found. Set Ctl.
type Realtime struct {
	Config      string // default DefaultRealtimeConfig
	Log         string // default DefaultRealtimeLog
	DatabaseDir string // default DefaultDatabaseDir
	Ctl         RealtimeController

	mu sync.Mutex
}

func (r *Realtime) config() string { return or(r.Config, DefaultRealtimeConfig) }
func (r *Realtime) log() string    { return or(r.Log, DefaultRealtimeLog) }
func (r *Realtime) dbDir() string  { return or(r.DatabaseDir, DefaultDatabaseDir) }

// RealtimeConfig is clamd.conf for the real-time mode: clamd on the
// distribution's socket, one database load at a time, and clamonacc
// watching the homes, report only. Homes that are not plain absolute paths
// are left out.
func RealtimeConfig(homes []string, dbDir string) []byte {
	var b strings.Builder

	w := func(s ...string) { b.WriteString(strings.Join(s, " ") + "\n") }

	b.WriteString("# Generated by the hostashi agent (ADR-0064). Do not edit: changes are overwritten.\n")
	w("LocalSocket", RealtimeSocket)
	w("FixStaleSocket", "yes")
	w("LocalSocketGroup", "clamav")
	w("LocalSocketMode", "666")
	w("User", "clamav")
	w("DatabaseDirectory", dbDir)
	w("LogSyslog", "no")
	w("LogTime", "no")
	// One engine in memory: scans wait while the signatures reload.
	w("ConcurrentDatabaseReload", "no")

	sorted := slices.Clone(homes)
	slices.Sort(sorted)
	sorted = slices.Compact(sorted)

	for _, h := range sorted {
		if !safePath(h) {
			continue
		}

		for _, d := range Excluded {
			w("ExcludePath", "^"+regexp.QuoteMeta(h+"/"+d+"/"))
		}

		w("OnAccessIncludePath", h)
	}

	w("OnAccessExcludeUname", "clamav")
	w("OnAccessExtraScanning", "yes")
	// Report only: a finding never blocks a read or a write.
	w("OnAccessPrevention", "no")

	return []byte(b.String())
}

// Sync writes the configuration for homes and restarts clamonacc when it
// changed or is not running, and clamd when it changed or failed. It
// reports whether clamonacc runs.
func (r *Realtime) Sync(ctx context.Context, homes []string) (bool, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	content := RealtimeConfig(homes, r.dbDir())

	old, err := os.ReadFile(r.config())
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return false, err
	}

	changed := !bytes.Equal(old, content)
	if changed {
		if err := os.MkdirAll(filepath.Dir(r.config()), 0o755); err != nil {
			return false, err
		}

		if err := writeFile(r.config(), content); err != nil {
			return false, err
		}
	}

	clamd, err := r.Ctl.State(ctx, ClamdUnit)
	if err != nil {
		return false, err
	}

	// clamav-daemon.socket starts clamd on the first connection; a running
	// one reads changed exclusions only on a restart.
	if (changed && clamd == "active") || clamd == "failed" {
		if err := r.Ctl.Restart(ctx, ClamdUnit); err != nil {
			return false, err
		}
	}

	onacc, err := r.Ctl.State(ctx, ClamonaccUnit)
	if err != nil {
		return false, err
	}

	// clamonacc refuses to start without a path to watch.
	if len(homes) == 0 {
		return false, nil
	}

	if changed || onacc == "failed" || onacc == "inactive" {
		if err := r.Ctl.Restart(ctx, ClamonaccUnit); err != nil {
			return false, err
		}

		return false, nil
	}

	return onacc == "active", nil
}

// Poll reads the findings logged since cursor (scan.realtime.poll). homes
// maps site users to their homes; a line for a path outside them, for a
// file that is gone or no longer a regular file is dropped.
func (r *Realtime) Poll(homes map[string]string, cursor int64) (agentapi.ScanRealtimeFindings, error) {
	r.mu.Lock()
	defer r.mu.Unlock()

	out := agentapi.ScanRealtimeFindings{Findings: []agentapi.RealtimeFinding{}}

	f, err := os.OpenFile(r.log(), os.O_RDWR, 0)
	if errors.Is(err, fs.ErrNotExist) {
		return out, nil
	}

	if err != nil {
		return out, err
	}

	defer f.Close()

	fi, err := f.Stat()
	if err != nil {
		return out, err
	}

	size := fi.Size()
	if cursor < 0 {
		out.Cursor = size

		return out, nil
	}

	// A smaller log was emptied or replaced: read it from the start.
	if cursor > size {
		cursor = 0
	}

	if _, err := f.Seek(cursor, io.SeekStart); err != nil {
		return out, err
	}

	buf := make([]byte, min(size-cursor, maxRealtimeRead))
	if _, err := io.ReadFull(f, buf); err != nil {
		return out, err
	}

	// Only whole lines; the rest waits for the next poll. A line longer
	// than a whole read is skipped.
	end := bytes.LastIndexByte(buf, '\n') + 1
	if end == 0 && len(buf) == maxRealtimeRead {
		end = len(buf)
		out.Dropped++
	}

	out.Cursor = cursor + int64(end)
	out.Findings, out.Dropped = parseRealtime(buf[:end], homes, out.Dropped)

	if out.Cursor == size && size > realtimeLogKeep {
		if err := f.Truncate(0); err == nil {
			out.Cursor = 0
		}
	}

	return out, nil
}

// parseRealtime turns clamonacc's lines "<path>: <signature> FOUND" into
// findings, checked like ParseLog does for a scan.
func parseRealtime(b []byte, homes map[string]string, dropped int) ([]agentapi.RealtimeFinding, int) {
	findings := []agentapi.RealtimeFinding{}
	roots := map[string]*os.Root{}

	defer func() {
		for _, r := range roots {
			_ = r.Close()
		}
	}()

	seen := map[string]bool{}
	sc := bufio.NewScanner(bytes.NewReader(b))
	sc.Buffer(make([]byte, 4096), maxRealtimeRead)

	for sc.Scan() {
		line, ok := strings.CutSuffix(sc.Text(), " FOUND")
		if !ok {
			continue
		}

		i := strings.LastIndex(line, ": ")
		if i < 0 || len(findings) >= agentapi.MaxScanFindings {
			dropped++

			continue
		}

		p, sig := line[:i], line[i+2:]

		site, rel := siteOf(homes, p)
		if site == "" || agentapi.ValidateScanPath(rel) != nil || agentapi.ValidateSignature(sig) != nil || seen[site+"/"+rel] {
			dropped++

			continue
		}

		root, ok := roots[site]
		if !ok {
			var err error
			if root, err = os.OpenRoot(homes[site]); err != nil {
				dropped++

				continue
			}

			roots[site] = root
		}

		sum, size, err := hashFile(root, rel)
		if err != nil {
			dropped++

			continue
		}

		seen[site+"/"+rel] = true
		findings = append(findings, agentapi.RealtimeFinding{Site: site, ScanFinding: agentapi.ScanFinding{Path: rel, Signature: sig, SHA256: sum, Size: size}})
	}

	return findings, dropped
}

// siteOf finds the site whose home holds p, the longest home first.
func siteOf(homes map[string]string, p string) (site, rel string) {
	best := ""

	for s, h := range homes {
		if r, ok := strings.CutPrefix(p, h+"/"); ok && len(h) > len(best) {
			best, site, rel = h, s, r
		}
	}

	return site, rel
}
