// Package objcache runs the object caches of the sites (ADR-0045): one
// Valkey instance per site that turns it on, as the systemd unit
// hostashi-valkey@<site>.service. The unit runs as the site user in the
// site's slice and listens only on a Unix socket in a directory that only
// the site user may enter. This package renders the instance's config from
// a fixed template whose only variables are the site name and the size,
// writes the slice drop-in, and starts, restarts and stops the unit
// through a Controller. It never talks to Valkey itself.
package objcache

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"sync"
	"text/template"

	"github.com/maki-it/hostashi/internal/agentapi"
)

// Fixed places on a server.
const (
	// DefaultSocketDir holds one directory per site, created by the unit
	// (RuntimeDirectory=hostashi-valkey/%i, mode 0700, owned by the site).
	DefaultSocketDir = "/run/hostashi-valkey"
	DefaultUnitDir   = "/etc/systemd/system"
	// DropInName names the drop-in that puts the unit into the site's
	// slice, the same name the PHP units use.
	DropInName = "50-hostashi-slice.conf"
)

// Errors of the operations.
var (
	// ErrNoCache means the site has no object cache.
	ErrNoCache = errors.New("objcache: the site has no object cache")
	// ErrPaused means the site is disabled, so its cache is stopped.
	ErrPaused = errors.New("objcache: the site is disabled")
	// ErrStartFailed means the unit did not start; the cache is off.
	ErrStartFailed = errors.New("objcache: the cache did not start")
)

// Controller drives systemd (phpctl.CacheController on a server).
type Controller interface {
	DaemonReload(ctx context.Context) error
	// Start enables a unit and starts it; Stop stops and disables it.
	Start(ctx context.Context, unit string) error
	Stop(ctx context.Context, unit string) error
	Restart(ctx context.Context, unit string) error
	// Show returns the named properties of a unit.
	Show(ctx context.Context, unit string, props ...string) (map[string]string, error)
}

// Manager keeps the caches. Set at least Dir, Slice and Ctl.
type Manager struct {
	// Dir holds the configs <site>.conf and the state (root 0700). The
	// unit opens the config as root and hands it to valkey-server on
	// standard input, so the site user never reads this directory.
	Dir       string
	SocketDir string // default DefaultSocketDir
	UnitDir   string // default DefaultUnitDir
	// Slice names the slice of a site (siteslice.Name).
	Slice func(site string) string
	Ctl   Controller
	Log   *slog.Logger

	mu sync.Mutex
}

type siteState struct {
	MemoryMB int  `json:"memoryMb"`
	Paused   bool `json:"paused,omitempty"`
}

// Unit is the systemd unit of a site's cache.
func Unit(site string) string { return "hostashi-valkey@" + site + ".service" }

func (m *Manager) socketDir() string { return cmpOr(m.SocketDir, DefaultSocketDir) }
func (m *Manager) unitDir() string   { return cmpOr(m.UnitDir, DefaultUnitDir) }

func cmpOr(a, b string) string {
	if a != "" {
		return a
	}

	return b
}

// Socket is the socket a site's apps connect to.
func (m *Manager) Socket(site string) string {
	return m.socketDir() + "/" + site + "/valkey.sock"
}

func (m *Manager) log() *slog.Logger {
	if m.Log != nil {
		return m.Log
	}

	return slog.New(slog.DiscardHandler)
}

// configTmpl is the whole config of an instance. Cache only: no TCP, no
// persistence, LRU eviction at maxmemory. The default user keeps every
// command but the @admin ones (CONFIG, DEBUG, MODULE, REPLICAOF, SHUTDOWN,
// MONITOR, ACL, SAVE, ...); FLUSHALL, INFO and KEYS stay, cache plugins use
// them. No password: the socket's directory is the access control.
var configTmpl = template.Must(template.New("valkey").Parse(`# Generated by hostashi for site {{.Site}} (ADR-0045). Do not edit: changes are overwritten.
port 0
unixsocket {{.Socket}}
unixsocketperm 600
dir {{.Dir}}
save ""
appendonly no
maxmemory {{.MB}}mb
maxmemory-policy allkeys-lru
enable-protected-configs no
enable-debug-command no
enable-module-command no
user default on nopass ~* &* +@all -@admin
`))

// Render returns the config of a site's cache.
func (m *Manager) Render(site string, mb int) ([]byte, error) {
	if err := (agentapi.CacheApplyRequest{Site: site, MemoryMB: mb}).Validate(); err != nil {
		return nil, err
	}

	if mb == 0 {
		return nil, errors.New("objcache: no config for size 0")
	}

	var b bytes.Buffer

	err := configTmpl.Execute(&b, map[string]any{
		"Site": site, "Socket": m.Socket(site), "Dir": m.socketDir() + "/" + site, "MB": mb,
	})
	if err != nil {
		return nil, fmt.Errorf("objcache: render %s: %w", site, err)
	}

	return b.Bytes(), nil
}

func (m *Manager) statePath() string       { return filepath.Join(m.Dir, "state.json") }
func (m *Manager) conf(site string) string { return filepath.Join(m.Dir, site+".conf") }
func (m *Manager) dropInDir(site string) string {
	return filepath.Join(m.unitDir(), Unit(site)+".d")
}

func (m *Manager) load() (map[string]siteState, error) {
	b, err := os.ReadFile(m.statePath())
	if errors.Is(err, os.ErrNotExist) {
		return map[string]siteState{}, nil
	}

	if err != nil {
		return nil, fmt.Errorf("objcache: state: %w", err)
	}

	st := map[string]siteState{}
	if err := json.Unmarshal(b, &st); err != nil {
		return nil, fmt.Errorf("objcache: state: %w", err)
	}

	return st, nil
}

func (m *Manager) save(st map[string]siteState) error {
	b, err := json.MarshalIndent(st, "", "  ")
	if err != nil {
		return fmt.Errorf("objcache: state: %w", err)
	}

	return writeAtomic(m.statePath(), append(b, '\n'), 0o600)
}

// Apply turns the cache of a site on with mb MiB, changes its size, or
// with mb 0 turns it off. A new or resized cache starts empty. While the
// site is paused (SetPaused) the config is kept and the unit stays off.
func (m *Manager) Apply(ctx context.Context, site string, mb int) (agentapi.CacheStatus, error) {
	if err := (agentapi.CacheApplyRequest{Site: site, MemoryMB: mb}).Validate(); err != nil {
		return agentapi.CacheStatus{}, err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return agentapi.CacheStatus{}, err
	}

	if mb == 0 {
		if err := m.remove(ctx, st, site); err != nil {
			return agentapi.CacheStatus{}, err
		}

		return agentapi.CacheStatus{Site: site}, nil
	}

	content, err := m.Render(site, mb)
	if err != nil {
		return agentapi.CacheStatus{}, err
	}

	if err := os.MkdirAll(m.Dir, 0o700); err != nil {
		return agentapi.CacheStatus{}, fmt.Errorf("objcache: %w", err)
	}

	cur, had := st[site]

	confChanged, err := writeIfChanged(m.conf(site), content, 0o600)
	if err != nil {
		return agentapi.CacheStatus{}, err
	}

	dropChanged, err := m.writeDropIn(site)
	if err != nil {
		return agentapi.CacheStatus{}, err
	}

	if dropChanged {
		if err := m.Ctl.DaemonReload(ctx); err != nil {
			return agentapi.CacheStatus{}, err
		}
	}

	next := siteState{MemoryMB: mb, Paused: cur.Paused}
	st[site] = next

	if err := m.save(st); err != nil {
		return agentapi.CacheStatus{}, err
	}

	if !next.Paused {
		unit := Unit(site)
		if had && (confChanged || dropChanged) {
			err = m.Ctl.Restart(ctx, unit)
		} else {
			err = m.Ctl.Start(ctx, unit)
		}

		if err != nil {
			m.log().ErrorContext(ctx, "object cache did not start", "site", site, "err", err)
			m.undo(ctx, st, site, cur, had)

			return agentapi.CacheStatus{}, fmt.Errorf("%w: site %s", ErrStartFailed, site)
		}

		m.log().InfoContext(ctx, "object cache ready", "site", site, "memoryMb", mb)
	}

	return m.status(ctx, site, next), nil
}

// undo puts a site back as it was before a failed Apply: the old size, or
// no cache. Failures are only logged.
func (m *Manager) undo(ctx context.Context, st map[string]siteState, site string, cur siteState, had bool) {
	undo := context.WithoutCancel(ctx)

	if !had {
		if err := m.remove(undo, st, site); err != nil {
			m.log().ErrorContext(ctx, "remove object cache after failed start", "site", site, "err", err)
		}

		return
	}

	content, err := m.Render(site, cur.MemoryMB)
	if err == nil {
		_, err = writeIfChanged(m.conf(site), content, 0o600)
	}

	if err == nil {
		st[site] = cur
		err = m.save(st)
	}

	if err == nil && !cur.Paused {
		err = m.Ctl.Restart(undo, Unit(site))
	}

	if err != nil {
		m.log().ErrorContext(ctx, "restore previous object cache", "site", site, "err", err)
	}
}

// remove stops a site's cache and deletes its config, drop-in and state.
func (m *Manager) remove(ctx context.Context, st map[string]siteState, site string) error {
	if _, ok := st[site]; !ok {
		return nil
	}

	if err := m.Ctl.Stop(ctx, Unit(site)); err != nil {
		return err
	}

	if err := os.Remove(m.conf(site)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("objcache: %w", err)
	}

	dir := m.dropInDir(site)
	if err := os.Remove(filepath.Join(dir, DropInName)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("objcache: %w", err)
	}

	if err := os.Remove(dir); err != nil && !errors.Is(err, os.ErrNotExist) {
		m.log().InfoContext(ctx, "cache drop-in directory not empty, kept", "site", site, "dir", dir)
	}

	if err := m.Ctl.DaemonReload(ctx); err != nil {
		m.log().ErrorContext(ctx, "daemon-reload after removing a cache", "site", site, "err", err)
	}

	delete(st, site)

	if err := m.save(st); err != nil {
		return err
	}

	m.log().InfoContext(ctx, "object cache removed", "site", site)

	return nil
}

// Remove turns a site's cache off, for site.delete. A site without one is
// not an error.
func (m *Manager) Remove(ctx context.Context, site string) error {
	if err := agentapi.ValidateSiteUser(site); err != nil {
		return err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return err
	}

	return m.remove(ctx, st, site)
}

// Flush empties a site's cache by restarting it: without persistence a
// restart starts empty.
func (m *Manager) Flush(ctx context.Context, site string) (agentapi.CacheStatus, error) {
	if err := agentapi.ValidateSiteUser(site); err != nil {
		return agentapi.CacheStatus{}, err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return agentapi.CacheStatus{}, err
	}

	cur, ok := st[site]

	switch {
	case !ok:
		return agentapi.CacheStatus{}, ErrNoCache
	case cur.Paused:
		return agentapi.CacheStatus{}, ErrPaused
	}

	if err := m.Ctl.Restart(ctx, Unit(site)); err != nil {
		m.log().ErrorContext(ctx, "flush object cache", "site", site, "err", err)

		return agentapi.CacheStatus{}, fmt.Errorf("%w: site %s", ErrStartFailed, site)
	}

	m.log().InfoContext(ctx, "object cache flushed", "site", site)

	return m.status(ctx, site, cur), nil
}

// SetPaused stops the cache of a disabled site and starts it again when the
// site is enabled; the config stays. A site without a cache is left alone.
func (m *Manager) SetPaused(ctx context.Context, site string, paused bool) error {
	if err := agentapi.ValidateSiteUser(site); err != nil {
		return err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return err
	}

	cur, ok := st[site]
	if !ok || cur.Paused == paused {
		return nil
	}

	if paused {
		err = m.Ctl.Stop(ctx, Unit(site))
	} else {
		err = m.Ctl.Start(ctx, Unit(site))
	}

	if err != nil {
		return err
	}

	cur.Paused = paused
	st[site] = cur

	return m.save(st)
}

// Status reports a site's cache; a site without one has MemoryMB 0.
func (m *Manager) Status(ctx context.Context, site string) (agentapi.CacheStatus, error) {
	if err := agentapi.ValidateSiteUser(site); err != nil {
		return agentapi.CacheStatus{}, err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return agentapi.CacheStatus{}, err
	}

	cur, ok := st[site]
	if !ok {
		return agentapi.CacheStatus{Site: site}, nil
	}

	return m.status(ctx, site, cur), nil
}

// Sites returns the sites with a cache and their state, by name.
func (m *Manager) Sites() (map[string]agentapi.CacheStatus, error) {
	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return nil, err
	}

	out := make(map[string]agentapi.CacheStatus, len(st))
	for s, c := range st {
		out[s] = agentapi.CacheStatus{Site: s, MemoryMB: c.MemoryMB, Socket: m.Socket(s), Paused: c.Paused}
	}

	return out, nil
}

func (m *Manager) status(ctx context.Context, site string, cur siteState) agentapi.CacheStatus {
	out := agentapi.CacheStatus{Site: site, MemoryMB: cur.MemoryMB, Socket: m.Socket(site), Paused: cur.Paused}

	props, err := m.Ctl.Show(ctx, Unit(site), "ActiveState", "MemoryCurrent")
	if err != nil {
		m.log().ErrorContext(ctx, "object cache state", "site", site, "err", err)

		return out
	}

	out.State = props["ActiveState"]
	if n, err := strconv.ParseUint(props["MemoryCurrent"], 10, 64); err == nil {
		out.UsedBytes = n
	}

	return out
}

// Recover starts the cache of every site that has one and is not paused.
// systemd starts enabled units at boot anyway; this repairs a unit whose
// drop-in or config was lost.
func (m *Manager) Recover(ctx context.Context) error {
	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return err
	}

	names := make([]string, 0, len(st))
	for s := range st {
		names = append(names, s)
	}

	slices.Sort(names)

	var errs []error

	for _, s := range names {
		if err := m.recoverSite(ctx, s, st[s]); err != nil {
			errs = append(errs, err)
		}
	}

	return errors.Join(errs...)
}

func (m *Manager) recoverSite(ctx context.Context, site string, cur siteState) error {
	content, err := m.Render(site, cur.MemoryMB)
	if err != nil {
		return err
	}

	confChanged, err := writeIfChanged(m.conf(site), content, 0o600)
	if err != nil {
		return err
	}

	dropChanged, err := m.writeDropIn(site)
	if err != nil {
		return err
	}

	if dropChanged {
		if err := m.Ctl.DaemonReload(ctx); err != nil {
			return err
		}
	}

	switch {
	case cur.Paused:
		return nil
	case confChanged || dropChanged:
		return m.Ctl.Restart(ctx, Unit(site))
	default:
		return m.Ctl.Start(ctx, Unit(site))
	}
}

// writeDropIn puts the unit into the site's slice (ADR-0015), so the
// cache's memory counts against the site's MemoryMax.
func (m *Manager) writeDropIn(site string) (bool, error) {
	if m.Slice == nil {
		return false, errors.New("objcache: no slice function")
	}

	content := []byte("# Generated by hostashi for site " + site + " (ADR-0015, ADR-0045). Do not edit: changes are overwritten.\n" +
		"[Service]\nSlice=" + m.Slice(site) + "\n")

	dir := m.dropInDir(site)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return false, fmt.Errorf("objcache: %w", err)
	}

	return writeIfChanged(filepath.Join(dir, DropInName), content, 0o644)
}

// writeIfChanged replaces name with data through a synced temporary file
// unless it already holds exactly that, and reports whether it wrote.
func writeIfChanged(name string, data []byte, mode os.FileMode) (bool, error) {
	if old, err := os.ReadFile(name); err == nil && bytes.Equal(old, data) {
		if st, err := os.Stat(name); err == nil && st.Mode().Perm() == mode {
			return false, nil
		}
	}

	return true, writeAtomic(name, data, mode)
}

func writeAtomic(name string, data []byte, mode os.FileMode) error {
	tmp := name + ".tmp"

	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o600)
	if err != nil {
		return fmt.Errorf("objcache: %w", err)
	}

	if _, err := f.Write(data); err != nil {
		_ = f.Close()

		return fmt.Errorf("objcache: %w", err)
	}

	if err := f.Chmod(mode); err != nil {
		_ = f.Close()

		return fmt.Errorf("objcache: %w", err)
	}

	if err := f.Sync(); err != nil {
		_ = f.Close()

		return fmt.Errorf("objcache: %w", err)
	}

	if err := f.Close(); err != nil {
		return fmt.Errorf("objcache: %w", err)
	}

	if err := os.Rename(tmp, name); err != nil {
		return fmt.Errorf("objcache: %w", err)
	}

	return nil
}
