// accessView is the rendered form of a site's setting; every value comes
// from a parsed prefix, a checked path or a fixed name.
type accessView struct {
	Allow, Deny []string
	// Realm, Fwd and Skip are variable names, empty without a password.
	Realm, Fwd, Skip string
	Bypass           []string
	// Paths are the map's regular expressions for the protected prefixes.
	Paths []string
	// File is the password file nginx's workers read.
	File string
}

func (n *Nginx) newAccessView(s Site) (*accessView, error) {
	a := s.Access
	if a.IsZero() {
		return nil, nil
	}

	v := &accessView{}

	list := make([]string, 0, len(a.IPs))
	for _, ip := range a.IPs {
		p, err := agentapi.ParsePrefix(ip)
		if err != nil {
			return nil, err
		}

		list = append(list, p.String())
	}

	switch a.IPMode {
	case agentapi.AccessIPAllow:
		v.Allow = list
	case agentapi.AccessIPDeny:
		v.Deny = list
	}

	if u := a.Auth; u != nil {
		if n.AuthDir == "" {
			return nil, errors.New("password protection needs a directory for password files")
		}

		suffix := hex.EncodeToString([]byte(s.User))
		v.Realm = "hostashi_realm_" + suffix
		v.Fwd = "hostashi_authz_" + suffix
		v.File = filepath.Join(n.AuthDir, AuthFileName(s))

		if len(u.Bypass) > 0 {
			v.Skip = "hostashi_noauth_" + suffix

			for _, b := range u.Bypass {
				p, err := agentapi.ParsePrefix(b)
				if err != nil {
					return nil, err
				}

				v.Bypass = append(v.Bypass, p.String())
			}
		}

		lead := ""
		if v.Skip != "" {
			lead = "0"
		}

		for _, p := range u.Paths {
			v.Paths = append(v.Paths, "~*^"+lead+accessPathRegex(agentapi.NormalAccessPath(p))+"(/|$)")
		}
	}

	return v, nil
}

// accessPathRegex quotes a checked path for a regular expression: of its
// characters only "." is special, and "[.]" needs no backslash inside an
// nginx string.
func accessPathRegex(p string) string { return strings.ReplaceAll(p, ".", "[.]") }

// AuthFileContent is the password file of a site: one "name:hash" line per
// user, from checked values only.
func AuthFileContent(s Site) []byte {
	if s.Access.Auth == nil {
		return nil
	}

	var b strings.Builder

	b.WriteString("# Generated by hostashi for site " + s.User + " (ADR-0066). Do not edit.\n")

	for _, u := range s.Access.Auth.Users {
		b.WriteString(u.Name + ":" + u.Hash + "\n")
	}

	return []byte(b.String())
}

// AuthFileName names a site's password file after its content, so a
// generation that is rolled back still points at its own file.
func AuthFileName(s Site) string {
	h := sha256.Sum256(AuthFileContent(s))

	return s.User + "-" + hex.EncodeToString(h[:8]) + ".htpasswd"
}

// AuthFiles writes and removes the password files below Dir. Dir is
// root:GID 0750 and each file root:GID 0640: nginx's workers (group GID)
// read them on every protected request, site users cannot.
type AuthFiles struct {
	Dir string
	GID int
}

// Write puts the password file of every site with password protection
// into Dir; a file that is already there is left alone.
func (a AuthFiles) Write(sites []Site) error {
	if err := os.MkdirAll(a.Dir, 0o750); err != nil {
		return fmt.Errorf("web: password files: %w", err)
	}

	if err := os.Chown(a.Dir, 0, a.GID); err != nil {
		return fmt.Errorf("web: password files: %w", err)
	}

	if err := os.Chmod(a.Dir, 0o750); err != nil {
		return fmt.Errorf("web: password files: %w", err)
	}

	for _, s := range sites {
		if s.Access.Auth == nil {
			continue
		}

		p := filepath.Join(a.Dir, AuthFileName(s))
		if fi, err := os.Lstat(p); err == nil && fi.Mode().IsRegular() {
			continue
		}

		if err := a.write(p, AuthFileContent(s)); err != nil {
			return err
		}
	}

	return nil
}

func (a AuthFiles) write(p string, b []byte) error {
	tmp := p + ".tmp"
	_ = os.Remove(tmp)

	f, err := os.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_EXCL|unix.O_NOFOLLOW, 0o600)
	if err != nil {
		return fmt.Errorf("web: password file: %w", err)
	}

	_, werr := f.Write(b)
	if werr == nil {
		werr = f.Chown(0, a.GID)
	}

	if werr == nil {
		werr = f.Chmod(0o640)
	}

	if werr == nil {
		werr = f.Sync()
	}

	if cerr := f.Close(); werr == nil {
		werr = cerr
	}

	if werr == nil {
		werr = os.Rename(tmp, p)
	}

	if werr != nil {
		_ = os.Remove(tmp)

		return fmt.Errorf("web: password file: %w", werr)
	}

	return nil
}

// Prune removes every password file that none of sites uses. Call it only
// after the generation with these sites is live.
func (a AuthFiles) Prune(sites []Site) error {
	keep := map[string]bool{}

	for _, s := range sites {
		if s.Access.Auth != nil {
			keep[AuthFileName(s)] = true
		}
	}

	es, err := os.ReadDir(a.Dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	} else if err != nil {
		return fmt.Errorf("web: password files: %w", err)
	}

	var errs []error

	for _, e := range es {
		if !keep[e.Name()] {
			if err := os.Remove(filepath.Join(a.Dir, e.Name())); err != nil && !errors.Is(err, fs.ErrNotExist) {
				errs = append(errs, err)
			}
		}
	}

	return errors.Join(errs...)
}
