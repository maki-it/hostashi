func TestEnvFileContent(t *testing.T) {
	got := string(EnvFileContent("shop", []agentapi.AppEnvVar{
		{Name: "DATABASE_URL", Value: `postgres://u:p@x/db?a=1&b="2"`},
		{Name: "TRICKY", Value: "$HOME `id` \\n %h ' #x"},
		{Name: "EMPTY"},
	}))

	want := "# Generated by hostashi for site shop (ADR-0054). Do not edit: changes are overwritten.\n" +
		`DATABASE_URL="postgres://u:p@x/db?a=1&b=\"2\""` + "\n" +
		"TRICKY=\"\\$HOME \\`id\\` \\\\n %h ' #x\"\n" +
		`EMPTY=""` + "\n"
	if got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
}

func TestApplyEnv(t *testing.T) {
	e := newEnv(t)
	ctx := context.Background()
	dir := filepath.Join(e.root, "units", "hostashi-node@shop.service.d")
	envPath := filepath.Join(dir, EnvFile)

	withEnv := spec(func(a *agentapi.AppSpec) {
		a.Env = []agentapi.AppEnvVar{{Name: "API_KEY", Value: "s3cr3t"}, {Name: "NODE_ENV", Value: "staging"}}
	})

	if _, err := e.m.Apply(ctx, withEnv); err != nil {
		t.Fatal(err)
	}

	fi, err := os.Stat(envPath)
	if err != nil || fi.Mode().Perm() != 0o600 {
		t.Fatalf("env file %v %v", fi, err)
	}

	b, _ := os.ReadFile(envPath)
	if !strings.Contains(string(b), "API_KEY=\"s3cr3t\"\n") {
		t.Fatalf("env file:\n%s", b)
	}

	app, _ := os.ReadFile(filepath.Join(dir, AppDropIn))
	if !strings.HasSuffix(string(app), "EnvironmentFile="+envPath+"\n") {
		t.Fatalf("drop-in:\n%s", app)
	}

	// The state keeps no values.
	state, _ := os.ReadFile(filepath.Join(e.root, "state", stateFile))
	if strings.Contains(string(state), "s3cr3t") || strings.Contains(string(state), "API_KEY") {
		t.Fatalf("value in the state: %s", state)
	}

	// A changed value restarts the app, though no drop-in changed.
	e.ctl.calls = nil
	withEnv.Env[0].Value = "n3w"

	if _, err := e.m.Apply(ctx, withEnv); err != nil || !slices.Equal(e.ctl.calls, []string{"restart hostashi-node@shop.service", "start hostashi-node@shop.service"}) {
		t.Fatalf("changed value: %v %v", err, e.ctl.calls)
	}

	// Recover keeps the file and its line, though the state has no values.
	if err := os.Remove(filepath.Join(dir, AppDropIn)); err != nil {
		t.Fatal(err)
	}

	if err := e.m.Recover(ctx); err != nil {
		t.Fatal(err)
	}

	app, _ = os.ReadFile(filepath.Join(dir, AppDropIn))
	if b, _ := os.ReadFile(envPath); !strings.Contains(string(b), "n3w") || !strings.Contains(string(app), "EnvironmentFile=") {
		t.Fatalf("after recover: %s\n%s", b, app)
	}

	// No variables: the file and its line go, the app restarts.
	e.ctl.calls = nil
	if _, err := e.m.Apply(ctx, spec(nil)); err != nil || e.ctl.calls[0] != "restart hostashi-node@shop.service" {
		t.Fatalf("without env: %v %v", err, e.ctl.calls)
	}

	app, _ = os.ReadFile(filepath.Join(dir, AppDropIn))
	if _, err := os.Stat(envPath); !errors.Is(err, os.ErrNotExist) || strings.Contains(string(app), "EnvironmentFile") {
		t.Fatalf("env left: %v\n%s", err, app)
	}

	// A link planted at the file's place is replaced, not followed.
	target := filepath.Join(e.root, "elsewhere")
	if err := os.Symlink(target, envPath); err != nil {
		t.Fatal(err)
	}

	if _, err := e.m.Apply(ctx, withEnv); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(target); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("link followed: %v", err)
	}

	if fi, err := os.Lstat(envPath); err != nil || !fi.Mode().IsRegular() {
		t.Fatalf("env file %v %v", fi, err)
	}

	// Removing the app removes the file.
	if err := e.m.Remove(ctx, "shop"); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(dir); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("drop-in directory left: %v", err)
	}
}

func TestEnvSpecRules(t *testing.T) {
	many := make([]agentapi.AppEnvVar, agentapi.MaxAppEnv+1)
	for i := range many {
		many[i] = agentapi.AppEnvVar{Name: fmt.Sprintf("V%d", i)}
	}

	big := make([]agentapi.AppEnvVar, 20)
	for i := range big {
		big[i] = agentapi.AppEnvVar{Name: fmt.Sprintf("V%d", i), Value: strings.Repeat("<", 1000)}
	}

	for name, env := range map[string][]agentapi.AppEnvVar{
		"lower case":  {{Name: "api_key"}},
		"digit first": {{Name: "1X"}},
		"reserved":    {{Name: "PORT", Value: "80"}},
		"path":        {{Name: "PATH", Value: "/tmp"}},
		"twice":       {{Name: "A"}, {Name: "A"}},
		"newline":     {{Name: "A", Value: "x\ny"}},
		"nul":         {{Name: "A", Value: "x\x00"}},
		"too long":    {{Name: "A", Value: strings.Repeat("x", agentapi.MaxAppEnvValue+1)}},
		"not utf-8":   {{Name: "A", Value: "\xff"}},
		"too many":    many,
		"too large":   big,
	} {
		if err := spec(func(a *agentapi.AppSpec) { a.Env = env }).Validate(); err == nil {
			t.Errorf("%s accepted", name)
		}
	}

	if err := spec(func(a *agentapi.AppSpec) {
		a.Env = []agentapi.AppEnvVar{{Name: "NODE_ENV", Value: "development"}, {Name: "_X1", Value: strings.Repeat("x", agentapi.MaxAppEnvValue)}}
	}).Validate(); err != nil {
		t.Fatal(err)
	}

	if s := fmt.Sprintf("%v %+v %#v", spec(func(a *agentapi.AppSpec) { a.Env = []agentapi.AppEnvVar{{Name: "K", Value: "s3cr3t"}} }), agentapi.AppEnvVar{Name: "K", Value: "s3cr3t"}, agentapi.AppEnvVar{Value: "s3cr3t"}); strings.Contains(s, "s3cr3t") {
		t.Fatalf("value printed: %s", s)
	}
}
