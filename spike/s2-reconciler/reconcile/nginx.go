// NginxDriver renders a self-contained nginx config per generation. All
// includes are relative to nginx.conf, so the same bytes work whether the
// generation is tested in generations/<n> or served through the "current"
// symlink. Commands run with argv arrays, never through a shell.
type NginxDriver struct {
	Binary      string // path to nginx
	RunDir      string // pid file, logs, temp dirs (not part of a generation)
	User        string // worker user
	ListenPort  int    // sites listen on 127.0.0.1:ListenPort (spike stand-in for 80/443)
	ControlPort int    // 127.0.0.1 control server that reports the live generation

	VerifyTimeout time.Duration
}

var mainTmpl = template.Must(template.New("main").Parse(`# generated by hostashi (spike S2), do not edit
daemon on;
user {{.User}};
worker_processes 1;
pid {{.RunDir}}/nginx.pid;
error_log {{.RunDir}}/error.log notice;
events { worker_connections 256; }
http {
    access_log off;
    client_body_temp_path {{.RunDir}}/tmp/body;
    proxy_temp_path {{.RunDir}}/tmp/proxy;
    fastcgi_temp_path {{.RunDir}}/tmp/fastcgi;
    uwsgi_temp_path {{.RunDir}}/tmp/uwsgi;
    scgi_temp_path {{.RunDir}}/tmp/scgi;
    server {
        listen 127.0.0.1:{{.ControlPort}};
        server_name _hostashi_control;
        location = /.hostashi/generation {
            default_type text/plain;
            include generation.conf;
        }
    }
    include sites/*.conf;
}
`))

var siteTmpl = template.Must(template.New("site").Parse(`# generated by hostashi (spike S2), site {{.Site.User}}
server {
    listen 127.0.0.1:{{.Port}};
    server_name{{range .Site.Domains}} {{.}}{{end}};
{{- if eq .Site.Kind "static"}}
    root {{.Site.Root}};
    index index.html;
    location / { try_files $uri $uri/ =404; }
{{- else}}
    location / {
        proxy_pass http://127.0.0.1:{{.Site.ProxyPort}};
        proxy_set_header Host $host;
    }
{{- end}}
    include snippets/{{.Site.User}}.conf;
}
`))

func (n *NginxDriver) Render(d Desired, gen int) (Files, error) {
	f := Files{Content: map[string][]byte{}, Meta: map[string][]byte{}}
	var b bytes.Buffer
	if err := mainTmpl.Execute(&b, n); err != nil {
		return f, err
	}
	f.Content["nginx.conf"] = append([]byte(nil), b.Bytes()...)
	for _, s := range d.Sites {
		b.Reset()
		if err := siteTmpl.Execute(&b, map[string]any{"Site": s, "Port": n.ListenPort}); err != nil {
			return f, err
		}
		f.Content["sites/"+s.User+".conf"] = append([]byte(nil), b.Bytes()...)
		snip := s.Snippet
		if snip == "" {
			snip = "# no custom directives"
		}
		f.Content["snippets/"+s.User+".conf"] = []byte(snip + "\n")
	}
	f.Meta["generation.conf"] = []byte(fmt.Sprintf("return 200 \"%d\";\n", gen))
	return f, nil
}

func (n *NginxDriver) run(ctx context.Context, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, n.Binary, args...)
	return cmd.CombinedOutput()
}

func (n *NginxDriver) ensureRunDir() error {
	return os.MkdirAll(filepath.Join(n.RunDir, "tmp"), 0o755)
}

func (n *NginxDriver) Validate(ctx context.Context, genDir string) error {
	if err := n.ensureRunDir(); err != nil {
		return err
	}
	out, err := n.run(ctx, "-t", "-p", n.RunDir, "-c", filepath.Join(genDir, "nginx.conf"))
	if err != nil {
		return fmt.Errorf("nginx -t: %w: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

func (n *NginxDriver) pid() (int, bool) {
	b, err := os.ReadFile(filepath.Join(n.RunDir, "nginx.pid"))
	if err != nil {
		return 0, false
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(b)))
	if err != nil || pid <= 1 {
		return 0, false
	}
	return pid, syscall.Kill(pid, 0) == nil
}

// Activate reloads a running server or starts a stopped one. A reload that
// nginx later rejects is not visible here; Verify detects that.
func (n *NginxDriver) Activate(ctx context.Context, currentDir string) error {
	if err := n.ensureRunDir(); err != nil {
		return err
	}
	conf := filepath.Join(currentDir, "nginx.conf")
	args := []string{"-p", n.RunDir, "-c", conf}
	if _, alive := n.pid(); alive {
		args = append(args, "-s", "reload")
	}
	if out, err := n.run(ctx, args...); err != nil {
		return fmt.Errorf("nginx %v: %w: %s", args[len(args)-1:], err, strings.TrimSpace(string(out)))
	}
	return nil
}

// Stop shuts the server down (used by tests, not by the reconciler).
func (n *NginxDriver) Stop(ctx context.Context, currentDir string) {
	if _, alive := n.pid(); alive {
		_, _ = n.run(ctx, "-p", n.RunDir, "-c", filepath.Join(currentDir, "nginx.conf"), "-s", "quit")
	}
}

var noKeepAlive = &http.Client{
	Timeout:   3 * time.Second,
	Transport: &http.Transport{DisableKeepAlives: true},
}

func get(ctx context.Context, port int, host, p string) (int, string, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, "http://"+net.JoinHostPort("127.0.0.1", strconv.Itoa(port))+p, nil)
	if err != nil {
		return 0, "", err
	}
	req.Host = host
	resp, err := noKeepAlive.Do(req)
	if err != nil {
		return 0, "", err
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<16))
	return resp.StatusCode, string(body), nil
}

// Verify waits until the control endpoint has reported generation gen several
// times in a row (a reload is asynchronous: for a short time old workers still
// accept connections, so one matching answer proves nothing), then asks every
// site for "/" on its primary domain. Any status >= 500 or transport error
// fails the generation.
func (n *NginxDriver) Verify(ctx context.Context, gen int, d Desired) error {
	timeout := n.VerifyTimeout
	if timeout == 0 {
		timeout = 5 * time.Second
	}
	const stableNeeded = 8
	deadline := time.Now().Add(timeout)
	want := strconv.Itoa(gen)
	var last string
	stable := 0
	for stable < stableNeeded {
		code, body, err := get(ctx, n.ControlPort, "_hostashi_control", "/.hostashi/generation")
		if err == nil && code == 200 && body == want {
			stable++
		} else {
			stable = 0
			last = fmt.Sprintf("status=%d body=%q err=%v", code, body, err)
		}
		if time.Now().After(deadline) {
			return fmt.Errorf("generation %d did not become live: %s", gen, last)
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(10 * time.Millisecond):
		}
	}
	for _, s := range d.Sites {
		code, _, err := get(ctx, n.ListenPort, s.Domains[0], "/")
		if err != nil {
			return fmt.Errorf("site %s: %w", s.User, err)
		}
		if code >= 500 {
			return fmt.Errorf("site %s: health check status %d", s.User, code)
		}
	}
	return nil
}
