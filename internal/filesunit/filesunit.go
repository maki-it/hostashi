// Package filesunit keeps the file manager's units of the sites (ADR-0040):
// hostashi-files@<site>.socket listens for the panel, and systemd starts
// hostashi-files@<site>.service on a connection. The template runs the
// helper as the site user; a drop-in per site puts it into the site's slice
// (ADR-0015) and mounts only the site's home, writable.
//
// The agent calls Open before the panel connects and Remove when a site is
// deleted. A Controller makes systemd act (internal/phpctl on a server).
package filesunit

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"log/slog"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sync"

	"github.com/maki-it/hostashi/internal/agentapi"
)

// DefaultUnitDir is where the drop-ins go.
const DefaultUnitDir = "/etc/systemd/system"

// DropInName is the drop-in of a site's helper unit.
const DropInName = "50-hostashi-site.conf"

// ErrInvalid is returned for a site the units cannot be written for.
var ErrInvalid = errors.New("filesunit: invalid site")

// Controller makes systemd act on the units.
type Controller interface {
	DaemonReload(ctx context.Context) error
	// Start starts a socket unit.
	Start(ctx context.Context, unit string) error
	// Restart restarts a running service unit and leaves a stopped one.
	Restart(ctx context.Context, unit string) error
	// Stop stops a socket or service unit.
	Stop(ctx context.Context, unit string) error
}

// Site is what the units need of a site.
type Site struct {
	Name  string
	Home  string
	Slice string
}

var (
	homeRe  = regexp.MustCompile(`^/[A-Za-z0-9_./-]+$`)
	sliceRe = regexp.MustCompile(`^hostashi-site-[A-Za-z0-9_\\-]+\.slice$`)
)

func (s Site) validate() error {
	if err := agentapi.ValidateSiteUser(s.Name); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalid, err)
	}

	if !homeRe.MatchString(s.Home) || path.Clean(s.Home) != s.Home || s.Home == "/" {
		return fmt.Errorf("%w: site %s: home %q", ErrInvalid, s.Name, s.Home)
	}

	if !sliceRe.MatchString(s.Slice) {
		return fmt.Errorf("%w: site %s: slice %q", ErrInvalid, s.Name, s.Slice)
	}

	return nil
}

// SocketUnit and ServiceUnit name a site's units.
func SocketUnit(site string) string  { return "hostashi-files@" + site + ".socket" }
func ServiceUnit(site string) string { return "hostashi-files@" + site + ".service" }

// Manager writes the drop-ins and starts the sockets.
type Manager struct {
	UnitDir string
	Ctl     Controller
	Log     *slog.Logger

	mu sync.Mutex
}

func (m *Manager) log() *slog.Logger {
	if m.Log == nil {
		return slog.New(slog.DiscardHandler)
	}

	return m.Log
}

func (m *Manager) dropInDir(site string) string {
	return filepath.Join(m.UnitDir, ServiceUnit(site)+".d")
}

func dropIn(s Site) []byte {
	// The template hides /home (ProtectHome=tmpfs) and makes the system
	// read only (ProtectSystem=strict); only the site's own home comes back,
	// writable. validate has checked that the home is a plain path.
	return []byte("# Generated by hostashi for site " + s.Name + " (ADR-0040). Do not edit: changes are overwritten.\n" +
		"[Service]\nSlice=" + s.Slice + "\nBindPaths=" + s.Home + "\nReadWritePaths=" + s.Home +
		"\nEnvironment=HOSTASHI_FILES_HOME=" + s.Home + "\n")
}

// Open writes the site's drop-in if it changed and starts its socket. It
// returns the socket path.
func (m *Manager) Open(ctx context.Context, s Site) (string, error) {
	if err := s.validate(); err != nil {
		return "", err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	dir := m.dropInDir(s.Name)
	file := filepath.Join(dir, DropInName)
	content := dropIn(s)

	if old, err := os.ReadFile(file); err != nil || !bytes.Equal(old, content) {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return "", fmt.Errorf("filesunit: %w", err)
		}

		if err := writeAtomic(file, content); err != nil {
			return "", err
		}

		if err := m.Ctl.DaemonReload(ctx); err != nil {
			return "", err
		}

		// A helper still running with an old home must not keep serving it.
		if err := m.Ctl.Restart(ctx, ServiceUnit(s.Name)); err != nil {
			return "", err
		}

		m.log().InfoContext(ctx, "file manager unit written", "site", s.Name)
	}

	if err := m.Ctl.Start(ctx, SocketUnit(s.Name)); err != nil {
		return "", err
	}

	return agentapi.FilesSocket(s.Name), nil
}

// Remove stops a site's socket and helper and deletes its drop-in. A site
// that never had them counts as done.
func (m *Manager) Remove(ctx context.Context, site string) error {
	if err := agentapi.ValidateSiteUser(site); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalid, err)
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	dir := m.dropInDir(site)
	if _, err := os.Stat(dir); errors.Is(err, os.ErrNotExist) {
		return nil
	}

	var errs []error

	for _, u := range []string{SocketUnit(site), ServiceUnit(site)} {
		if err := m.Ctl.Stop(ctx, u); err != nil {
			errs = append(errs, err)
		}
	}

	if err := os.Remove(filepath.Join(dir, DropInName)); err != nil && !errors.Is(err, os.ErrNotExist) {
		errs = append(errs, fmt.Errorf("filesunit: %w", err))
	}

	if err := os.Remove(dir); err != nil && !errors.Is(err, os.ErrNotExist) {
		m.log().InfoContext(ctx, "file manager drop-in directory not empty, kept", "site", site, "dir", dir)
	}

	if err := m.Ctl.DaemonReload(ctx); err != nil {
		errs = append(errs, err)
	}

	return errors.Join(errs...)
}

func writeAtomic(file string, content []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(file), ".hostashi-*")
	if err != nil {
		return fmt.Errorf("filesunit: %w", err)
	}

	name := tmp.Name()

	_, werr := tmp.Write(content)
	cerr := tmp.Close()

	if err := errors.Join(werr, cerr, os.Chmod(name, 0o644)); err != nil {
		_ = os.Remove(name)

		return fmt.Errorf("filesunit: %w", err)
	}

	if err := os.Rename(name, file); err != nil {
		_ = os.Remove(name)

		return fmt.Errorf("filesunit: %w", err)
	}

	return nil
}
