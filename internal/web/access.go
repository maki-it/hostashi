// Password protection and IP rules per site (ADR-0066). The IP rule and
// auth_basic go into every server block that serves the site. Which
// requests need a password is decided by a map on $uri (and a geo for the
// addresses that need none), so the site's own locations stay as they are.
// The ACME challenge and health locations always stay open.

// AccessRealm is the fixed text a browser shows in its password dialog.
const AccessRealm = "Restricted"

const accessMapSrc = `{{define "accessmap"}}
{{- with .}}
{{- if .Realm}}
{{- if .Skip}}

# Password protection (ADR-0066): 1 for the addresses that need no password.
geo ${{.Skip}} {
    default 0;
    {{- range .Bypass}}
    {{.}} 1;
    {{- end}}
}
{{- end}}

# Password protection (ADR-0066): the realm for requests that need a
# password, off for the others.
map {{if .Skip}}"${{.Skip}}$uri"{{else}}$uri{{end}} ${{.Realm}} {
    default {{if .Paths}}off{{else}}"` + AccessRealm + `"{{end}};
    {{- if .Skip}}
    "~^1" off;
    {{- end}}
    {{- range .Paths}}
    "{{.}}" "` + AccessRealm + `";
    {{- end}}
}

# The visitor's password never reaches the application; its own
# Authorization header still does where no password is asked.
map ${{.Realm}} ${{.Fwd}} {
    default "";
    off $http_authorization;
}
{{- end}}
{{- end}}
{{- end}}`

const accessSrc = `{{define "access"}}
{{- with .}}
    # Access protection of the site (ADR-0066).
    {{- range .Allow}}
    allow {{.}};
    {{- end}}
    {{- range .Deny}}
    deny {{.}};
    {{- end}}
    {{- if .Allow}}
    deny all;
    {{- else if .Deny}}
    allow all;
    {{- end}}
    {{- if .Realm}}
    auth_basic ${{.Realm}};
    auth_basic_user_file {{.File}};
    {{- end}}
{{- end}}
{{- end}}`

