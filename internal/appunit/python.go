// The Python environment of a site (ADR-0061): <home>/.venv, made by the
// oneshot unit hostashi-python-venv@<site> as the site user, from the
// fixed template and a drop-in with typed values.
const (
	// VenvDropIn names the drop-in with the venv command.
	VenvDropIn = "60-hostashi-venv.conf"
	// VenvLog is the output of the last run, next to app.log.
	VenvLog = "venv.log"
	// venvLogTail is how much of the log an error carries.
	venvLogTail = 2048
)

// VenvDropInContent makes <home>/.venv with the line's interpreter:
// python3 -m venv [--clear] <home>/.venv. pip comes from the build's own
// ensurepip, offline.
func VenvDropInContent(pythonDir, site, line string, acct Site, wipe bool) ([]byte, error) {
	if err := agentapi.ValidateSiteUser(site); err != nil {
		return nil, err
	}

	if err := agentapi.ValidatePythonLine(line); err != nil {
		return nil, err
	}

	if !safePath(acct.Home) || !safePath(pythonDir) {
		return nil, fmt.Errorf("appunit: invalid home %q or Python directory %q", acct.Home, pythonDir)
	}

	cmd := path.Join(pythonDir, line, "bin", "python3") + " -m venv"
	if wipe {
		cmd += " --clear"
	}

	cmd += " " + Quote(acct.Home+"/"+agentapi.PythonVenvDir)

	return []byte("# Generated by hostashi for site " + site + " (ADR-0061). Do not edit: changes are overwritten.\n" +
		"[Service]\n" +
		"WorkingDirectory=" + acct.Home + "\n" +
		"ExecStart=\n" +
		"ExecStart=" + cmd + "\n" +
		"Environment=HOME=" + acct.Home + " USER=" + site + " LOGNAME=" + site + "\n" +
		"Environment=PATH=/usr/local/bin:/usr/bin:/bin\n"), nil
}

func safePath(p string) bool {
	return filepath.IsAbs(p) && filepath.Clean(p) == p && !strings.ContainsAny(p, " \t\n\"'\\%$")
}

// venvThere reports whether the site has <home>/.venv/bin/python (a link
// to the line's interpreter, not followed).
func venvThere(acct Site) bool {
	root, err := os.OpenRoot(acct.Home)
	if err != nil {
		return false
	}
	defer root.Close()

	_, err = root.Lstat(agentapi.PythonVenvDir + "/bin/python")

	return err == nil
}

// makeVenv writes the venv unit's drop-ins and runs it; m.mu is held.
func (m *Manager) makeVenv(ctx context.Context, site, line string, acct Site, wipe bool) error {
	unit := VenvUnit(site)

	content, err := VenvDropInContent(m.pythonDir(), site, line, acct, wipe)
	if err != nil {
		return err
	}

	var hidden []string
	if m.Hidden != nil {
		hidden = m.Hidden()
	}

	logs := filepath.Join(m.logDir(), site)
	if err := os.MkdirAll(logs, 0o700); err != nil {
		return fmt.Errorf("appunit: %w", err)
	}

	dir := m.dropInDir(unit)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("appunit: %w", err)
	}

	c1, err := writeIfChanged(filepath.Join(dir, SliceDropIn), SliceDropInContent(site, acct, hidden))
	if err != nil {
		return err
	}

	c2, err := writeIfChanged(filepath.Join(dir, VenvDropIn), content)
	if err != nil {
		return err
	}

	if c1 || c2 {
		if err := m.Ctl.DaemonReload(ctx); err != nil {
			return err
		}
	}

	_ = m.Ctl.ResetFailed(ctx, unit)

	if err := m.Ctl.Run(ctx, unit); err != nil {
		tail := logTail(filepath.Join(logs, VenvLog))
		m.log().ErrorContext(ctx, "python venv", "site", site, "line", line, "err", err, "log", tail)

		if tail != "" {
			return fmt.Errorf("%w: %s", ErrVenv, tail)
		}

		return fmt.Errorf("%w: %w", ErrVenv, err)
	}

	m.log().InfoContext(ctx, "python venv created", "site", site, "line", line, "clear", wipe)

	return nil
}

// logTail is the end of a log, at most venvLogTail bytes, "" if there is
// none.
func logTail(name string) string {
	f, err := os.Open(name)
	if err != nil {
		return ""
	}
	defer f.Close()

	if fi, err := f.Stat(); err == nil && fi.Size() > venvLogTail {
		_, _ = f.Seek(-venvLogTail, io.SeekEnd)
	}

	b, _ := io.ReadAll(io.LimitReader(f, venvLogTail))

	return strings.TrimSpace(strings.ToValidUTF8(string(b), "?"))
}

// pythonProblem checks what a Python app that should run needs below the
// home: the environment, made with the app's line, and for wsgi and asgi
// the app server in its site-packages. Nothing is run; the files are read
// through os.Root without following links out of the home. As for the
// program of a binary app, this is for the panel's message only.
func (m *Manager) pythonProblem(a agentapi.AppSpec, acct Site) string {
	if a.Stopped || a.StartKind == "" {
		return ""
	}

	root, err := os.OpenRoot(acct.Home)
	if err != nil {
		return "the home cannot be opened"
	}
	defer root.Close()

	venv := agentapi.PythonVenvDir

	if _, err := root.Lstat(venv + "/bin/python"); err != nil {
		return "the Python environment .venv is missing; recreate it in the panel"
	}

	if home := venvHome(root); home != path.Join(m.pythonDir(), a.Python, "bin") {
		return "the Python environment .venv was not made with Python " + a.Python + "; recreate it in the panel"
	}

	server := map[string]string{agentapi.AppStartWSGI: "gunicorn", agentapi.AppStartASGI: "uvicorn"}[a.StartKind]
	if server == "" {
		return ""
	}

	fi, err := root.Lstat(venv + "/lib/python" + a.Python + "/site-packages/" + server)
	if err != nil || !fi.IsDir() {
		return server + " is not installed in .venv: run " + venv + "/bin/pip install " + server
	}

	return ""
}

// venvHome is the home key of .venv/pyvenv.cfg: the directory of the
// interpreter the environment was made with.
func venvHome(root *os.Root) string {
	f, err := root.Open(agentapi.PythonVenvDir + "/pyvenv.cfg")
	if err != nil {
		return ""
	}
	defer f.Close()

	sc := bufio.NewScanner(io.LimitReader(f, 16<<10))
	for sc.Scan() {
		k, v, ok := strings.Cut(sc.Text(), "=")
		if ok && strings.TrimSpace(k) == "home" {
			return strings.TrimSpace(v)
		}
	}

	return ""
}

// Venv makes a site's Python environment (site.python.venv), with clear a
// new one in place of the old: its packages are gone. A Python app of the
// site restarts on it, or stays stopped while its app server is missing.
func (m *Manager) Venv(ctx context.Context, req agentapi.PythonVenvRequest) (agentapi.AppStatus, error) {
	if err := req.Validate(); err != nil {
		return agentapi.AppStatus{}, err
	}

	if !m.pythonInstalled(req.Python) {
		return agentapi.AppStatus{}, fmt.Errorf("%w: Python %s", ErrPythonMissing, req.Python)
	}

	acct, err := m.Site(req.Site)
	if err != nil {
		return agentapi.AppStatus{}, err
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	st, err := m.load()
	if err != nil {
		return agentapi.AppStatus{}, err
	}

	e, ok := st[req.Site]
	if ok && e.App.IsPython() && e.App.Python != req.Python {
		// The app is applied with the new line afterwards; until then
		// it must not run on an environment of another line.
		ok = false

		if err := m.Ctl.Stop(ctx, PythonUnit(req.Site)); err != nil {
			return agentapi.AppStatus{}, err
		}
	}

	if err := m.makeVenv(ctx, req.Site, req.Python, acct, req.Clear); err != nil {
		return agentapi.AppStatus{}, err
	}

	if !ok || !e.App.IsPython() {
		return agentapi.AppStatus{Site: req.Site}, nil
	}

	unit := PythonUnit(req.Site)
	problem := m.problem(e.App, acct)

	switch {
	case e.App.Stopped || problem != "":
		err = m.Ctl.Stop(ctx, unit)
	default:
		_ = m.Ctl.ResetFailed(ctx, unit)
		err = m.Ctl.Restart(ctx, unit)
	}

	if err != nil {
		return agentapi.AppStatus{}, fmt.Errorf("appunit: site %s: %w", req.Site, err)
	}

	out := m.status(ctx, e.App)
	out.Problem = problem

	return out, nil
}

// removeVenvUnit deletes the drop-ins of a site's venv unit. The
// environment itself is the site's and stays in its home.
func (m *Manager) removeVenvUnit(site string) error {
	dir := m.dropInDir(VenvUnit(site))
	for _, f := range []string{SliceDropIn, VenvDropIn} {
		if err := os.Remove(filepath.Join(dir, f)); err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("appunit: %w", err)
		}
	}

	_ = os.Remove(dir)

	return nil
}
