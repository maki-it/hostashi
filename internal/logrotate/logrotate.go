// Package logrotate renders the logrotate file of the logs Hostashi writes
// (ADR-0053): the nginx logs of every site, the server-wide nginx logs and
// the PHP error log of every site.
// The number of days is the only input; everything else is fixed here.
package logrotate

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"text/template"

	"github.com/maki-it/hostashi/internal/agentapi"
)

// The retention range in days (ADR-0053). The default matches what Kim's
// data processing agreement promises.
const (
	MinDays     = agentapi.MinLogRetentionDays
	MaxDays     = agentapi.MaxLogRetentionDays
	DefaultDays = agentapi.DefaultLogRetentionDays
)

// File is where the agent writes the configuration.
const File = "/etc/logrotate.d/hostashi"

// ErrDays is returned for a number of days outside MinDays..MaxDays.
var ErrDays = errors.New("logrotate: days out of range")

// Config is what goes into the file.
type Config struct {
	// SiteLogDir holds <site>/access.log and <site>/error.log.
	SiteLogDir string
	// ServerLogDir holds the server-wide access.log and error.log.
	ServerLogDir string
	// PHPLogDir holds <site>/error.log of each site's PHP-FPM master.
	PHPLogDir string
	// NginxPID is the pid file of the nginx master, which reopens its
	// logs on USR1.
	NginxPID string
	// Days is how long rotated logs are kept.
	Days int
}

//nolint:dupword // "root root" is owner and group
var tmpl = template.Must(template.New("logrotate").Parse(`# Generated by hostashi (ADR-0053). Do not edit: the log retention in the
# panel overwrites this file.
{{.SiteLogDir}}/*/*.log {{.ServerLogDir}}/*.log {
    daily
    rotate {{.Days}}
    maxage {{.Days}}
    missingok
    notifempty
    compress
    delaycompress
    create 0640 root root
    su root root
    sharedscripts
    postrotate
        [ ! -s {{.NginxPID}} ] || kill -USR1 "$(cat {{.NginxPID}})"
    endscript
}

{{.PHPLogDir}}/*/*.log {
    daily
    rotate {{.Days}}
    maxage {{.Days}}
    missingok
    notifempty
    compress
    delaycompress
    create 0640 root root
    su root root
    sharedscripts
    postrotate
        systemctl kill --kill-whom=main --signal=USR1 'hostashi-php-*@*.service' >/dev/null 2>&1 || true
    endscript
}
`))

// Render returns the file for c.
func Render(c Config) ([]byte, error) {
	if c.Days < MinDays || c.Days > MaxDays {
		return nil, fmt.Errorf("%w: %d", ErrDays, c.Days)
	}

	for _, p := range []string{c.SiteLogDir, c.ServerLogDir, c.PHPLogDir, c.NginxPID} {
		if !safePath(p) {
			return nil, fmt.Errorf("logrotate: invalid path %q", p)
		}
	}

	var b bytes.Buffer
	if err := tmpl.Execute(&b, c); err != nil {
		return nil, fmt.Errorf("logrotate: %w", err)
	}

	return b.Bytes(), nil
}

// safePath allows absolute clean paths of plain characters: the paths go
// into a configuration file and a shell line of logrotate.
func safePath(p string) bool {
	if p == "" || p[0] != '/' || filepath.Clean(p) != p {
		return false
	}

	for _, r := range p {
		ok := r == '/' || r == '-' || r == '_' || r == '.' ||
			(r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')
		if !ok {
			return false
		}
	}

	return true
}

// Write renders c into path atomically, mode 0644 as logrotate wants it.
func Write(path string, c Config) error {
	b, err := Render(c)
	if err != nil {
		return err
	}

	dir := filepath.Dir(path)

	tmp, err := os.CreateTemp(dir, ".hostashi-logrotate-*")
	if err != nil {
		return fmt.Errorf("logrotate: %w", err)
	}

	defer os.Remove(tmp.Name())

	if _, err := tmp.Write(b); err != nil {
		_ = tmp.Close()

		return fmt.Errorf("logrotate: %w", err)
	}

	if err := tmp.Chmod(0o644); err != nil {
		_ = tmp.Close()

		return fmt.Errorf("logrotate: %w", err)
	}

	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()

		return fmt.Errorf("logrotate: %w", err)
	}

	if err := tmp.Close(); err != nil {
		return fmt.Errorf("logrotate: %w", err)
	}

	if err := os.Rename(tmp.Name(), path); err != nil {
		return fmt.Errorf("logrotate: %w", err)
	}

	return nil
}

// Ensure brings the file up to date at agent start and keeps the retention
// an earlier Write stored in it; a missing or unreadable file gets
// DefaultDays. So a new version of the template reaches every server
// without the panel.
func Ensure(path string, c Config) error {
	c.Days = DefaultDays

	if b, err := os.ReadFile(path); err == nil {
		if d, ok := Days(b); ok {
			c.Days = d
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("logrotate: %w", err)
	}

	return Write(path, c)
}

var rotateRe = regexp.MustCompile(`(?m)^    rotate ([0-9]{1,3})$`)

// Days reads the retention from a file that Render wrote.
func Days(b []byte) (int, bool) {
	m := rotateRe.FindSubmatch(b)
	if m == nil {
		return 0, false
	}

	d, err := strconv.Atoi(string(m[1]))
	if err != nil || d < MinDays || d > MaxDays {
		return 0, false
	}

	return d, true
}
